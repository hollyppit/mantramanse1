export function repeatedAdvice(paragraphs,history,roles){
 const sentences=text=>String(text||'').split(/(?<=[.!?。])\s+|\n+/).map(t=>t.trim()).filter(t=>t.length>=25&&!/근거|자료|예측|보장|가정|전통|사주/.test(t));
 const key=text=>text.replace(/[\s\p{P}\p{S}]/gu,'');const prior=new Map();
 for(const row of history)for(const field of ['reinforce','practice','caution'])for(const text of sentences(row[field]))if(!prior.has(key(text)))prior.set(key(text),row.chapter);
 const out=[];for(const p of paragraphs){const role=p.role||roles.find(r=>r.id===p.id)?.role;if(!['reinforce','practice','risk'].includes(role))continue;for(const text of sentences(p.text)){const other=prior.get(key(text));if(other)out.push({code:'sentence-duplicate',id:p.id,other,reason:'이전 장과 동일한 생활 조언 문장입니다. 현재 질문의 결정 대상과 관찰 행동으로 구체화하거나 중복 설명을 줄이세요.'});}}
 return out;
}
