export const ADVICE_HISTORY_LIMIT=84;
export function cleanAdviceHistory(rows,currentId){
 if(!Array.isArray(rows))return [];
 const seen=new Set(),out=[];let chars=0;
 for(const row of rows.slice(-ADVICE_HISTORY_LIMIT).reverse()){
  if(!row||typeof row.chapter!=='string'||!/^[-\w.가-힣]{1,80}$/.test(row.chapter)||row.chapter===currentId||seen.has(row.chapter))continue;
  const item={chapter:row.chapter,title:typeof row.title==='string'?row.title.slice(0,150):''};
  for(const k of ['reinforce','practice','caution'])if(typeof row[k]==='string'&&row[k].trim()&&row[k].length<=500)item[k]=row[k];
  if(!item.reinforce&&!item.practice&&!item.caution)continue;
  const size=JSON.stringify(item).length;if(chars+size>60000)continue;
  seen.add(item.chapter);chars+=size;out.push(item);
 }
 return out.reverse();
}
