const sents = t => String(t || '').split(/(?<=[.!?。])\s+/).map(s => s.trim()).filter(Boolean);
const plain = s => s.replace(/[‘’“”'"]/g, '');
// 순위 목록의 2순위 이하 항목은 그 사람의 진단이 아니라 참고 목록이라 뺀다
const topOnly = t => String(t || '').replace(/(?<!\d)(?:[2-9]|1\d)순위 [\s\S]*?(?=(?<!\d)1순위 |$)/g, '');
// layers: { 층이름: 글 } → [{axis, a:{layer,side,s}, b:{layer,side,s}}] (축마다 하나, 서로 다른 층만)
function find(layers) {
  const out = [];
  for (const [axis, ln, lre, rn, rre] of AXES) {
    const hit = re => Object.entries(layers).flatMap(([layer, t]) => sents(layer === 'feature' ? topOnly(t) : t).filter(s => re.test(plain(s))).slice(0, 2).map(s => ({ layer, s })));
    const L = hit(lre), R = hit(rre);
    for (const a of L) {
      const b = R.find(x => x.layer !== a.layer && x.s !== a.s);
      if (b) { out.push({ axis, a: { layer: a.layer, side: ln, s: a.s }, b: { layer: b.layer, side: rn, s: b.s } }); break; }
    }
  }
  return out;
}
module.exports = { find, AXES };

