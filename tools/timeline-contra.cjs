  ['내 힘', '힘이 센 편', /(?:내|타고난) 힘이 (?:센|강한|넘치는)|힘이 (?:센|넘치는) (?:사주|쪽)|\(신강\)/, '힘이 여린 편', /(?:내|타고난) 힘이 (?:여린|약한)|힘이 여린 (?:사주|편)|\(신약\)/]
